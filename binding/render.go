package binding

import (
	"fmt"
	"strconv"
	"strings"
)

// Render writes a TypeScript declaration for window.__XGOEF__.
// cmds must already come from Assemble.
func Render(cmds []Command) (string, error) {
	norm := make([]Command, len(cmds))
	seen := map[string]bool{}
	for i, c := range cmds {
		n, err := Normalize(c)
		if err != nil {
			return "", err
		}
		if seen[n.Name] {
			return "", fmt.Errorf("binding: duplicate command %q", n.Name)
		}
		seen[n.Name] = true
		norm[i] = n
	}

	var b strings.Builder
	b.WriteString("// Generated by xgoef from xgoef.conf.json. Do not edit.\n\n")
	b.WriteString("export interface XgoefInvokeOptions {\n")
	b.WriteString("  timeout?: number;\n")
	b.WriteString("  signal?: AbortSignal;\n")
	b.WriteString("}\n\n")
	b.WriteString("export interface XgoefChannel {\n")
	b.WriteString("  readonly id: number;\n")
	b.WriteString("  onmessage(handler: (payload: unknown) => void): () => void;\n")
	b.WriteString("  close(): void;\n")
	b.WriteString("}\n\n")
	b.WriteString("export interface XgoefInvokeResult<T> extends Promise<T> {\n")
	b.WriteString("  cancel(): void;\n")
	b.WriteString("}\n\n")
	b.WriteString("export interface XgoefError extends Error {\n")
	b.WriteString("  readonly code: string;\n")
	b.WriteString("}\n\n")
	b.WriteString("export interface XgoefCommands {\n")
	if len(norm) == 0 {
		b.WriteString("  [cmd: string]: { args: Record<string, unknown>; result: unknown };\n")
	}
	for _, c := range norm {
		if c.Doc != "" {
			b.WriteString("  /** " + c.Doc + " */\n")
		}
		b.WriteString("  " + tsKey(c.Name) + ": { args: " + formatArgs(c.Args) + "; result: " + c.Result + " };\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("export interface Xgoef {\n")
	b.WriteString("  invoke<K extends keyof XgoefCommands>(\n")
	b.WriteString("    cmd: K,\n")
	b.WriteString("    args: XgoefCommands[K][\"args\"],\n")
	b.WriteString("    opts?: XgoefInvokeOptions,\n")
	b.WriteString("  ): XgoefInvokeResult<XgoefCommands[K][\"result\"]>;\n")
	b.WriteString("  listen(event: string, handler: (payload: unknown) => void): () => void;\n")
	b.WriteString("  emit(event: string, payload?: unknown): void;\n")
	b.WriteString("  channel(): XgoefChannel;\n")
	b.WriteString("  readonly XgoefError: new (code: string, message?: string) => XgoefError;\n")
	b.WriteString("  plugins: {\n")
	b.WriteString(renderPlugins(norm))
	b.WriteString("  };\n")
	b.WriteString("}\n\n")
	b.WriteString("declare global {\n")
	b.WriteString("  const __XGOEF__: Xgoef;\n")
	b.WriteString("  interface Window {\n")
	b.WriteString("    __XGOEF__: Xgoef;\n")
	b.WriteString("    __xgoefDispatch(msg: unknown): void;\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String(), nil
}

func renderPlugins(cmds []Command) string {
	var b strings.Builder
	for _, ns := range helperNS {
		var methods []Command
		for _, c := range cmds {
			plug, _, ok := strings.Cut(c.Name, ":")
			if ok && plug == ns {
				if _, known := helperMethod(c); known {
					methods = append(methods, c)
				}
			}
		}
		if len(methods) == 0 {
			continue
		}
		b.WriteString("    " + tsKey(ns) + ": {\n")
		for _, c := range methods {
			params, _ := helperMethod(c)
			_, method, _ := strings.Cut(c.Name, ":")
			b.WriteString("      " + camel(method) + "(" + params + "): XgoefInvokeResult<" + c.Result + ">;\n")
		}
		b.WriteString("    };\n")
	}
	return b.String()
}

// helperMethod reports the parameter list used by xgoef.js.
// The second result is false when this command has no plugins.* helper.
func helperMethod(c Command) (string, bool) {
	switch c.Name {
	case "shell:open":
		return "target: string", true
	case "dialog:open", "dialog:save":
		return "opts?: " + formatArgs(c.Args), true
	case "notification:show":
		return "opts: { title: string; body?: string; icon?: string } | string", true
	case "fs:read_text", "fs:write_text", "fs:exists", "fs:list",
		"os:platform", "os:arch",
		"clipboard:read_text", "clipboard:write_text",
		"updater:check", "updater:install",
		"process:exit", "process:relaunch",
		"notification:is_permission_granted", "notification:request_permission",
		"global-shortcut:register", "global-shortcut:unregister", "global-shortcut:unregister_all", "global-shortcut:is_registered",
		"monitor:list", "monitor:primary", "monitor:current", "monitor:scale", "monitor:move",
		"webview:print", "webview:open_dev_tools", "webview:close_dev_tools", "webview:is_dev_tools_open",
		"eval:run",
		"autostart:enable", "autostart:disable", "autostart:is_enabled",
		"log:write",
		"window:minimize", "window:maximize", "window:unminimize", "window:unmaximize", "window:toggle_maximize",
		"window:show", "window:hide", "window:center",
		"window:set_title", "window:set_always_on_top", "window:set_fullscreen", "window:set_size",
		"window:is_minimized", "window:is_maximized", "window:is_fullscreen", "window:is_always_on_top", "window:is_visible",
		"deeplink:get_current":
		return formatParams(c.Args), true
	default:
		return "", false
	}
}

func formatArgs(args []Arg) string {
	if len(args) == 0 {
		return "Record<string, never>"
	}
	var b strings.Builder
	b.WriteString("{ ")
	for i, a := range args {
		if i > 0 {
			b.WriteString("; ")
		}
		b.WriteString(a.Name)
		if a.Optional {
			b.WriteByte('?')
		}
		b.WriteString(": ")
		b.WriteString(a.Type)
	}
	b.WriteString(" }")
	return b.String()
}

func formatParams(args []Arg) string {
	parts := make([]string, len(args))
	for i, a := range args {
		op := ""
		if a.Optional {
			op = "?"
		}
		parts[i] = a.Name + op + ": " + a.Type
	}
	return strings.Join(parts, ", ")
}

func tsKey(name string) string {
	if ident(name) {
		return name
	}
	return strconv.Quote(name)
}

func camel(s string) string {
	parts := strings.Split(s, "_")
	var b strings.Builder
	for i, p := range parts {
		if p == "" {
			continue
		}
		if i == 0 {
			b.WriteString(p)
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}
